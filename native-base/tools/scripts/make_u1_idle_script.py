"""P8 option U, U-1's one-PC test (docs/research/s25/u0-resultados-s28.md §8): a cdmp_peer script in which user 2
logs in with a walk script's login, walks it, and then STANDS STILL sending one Req every --every-ms for --minutes
(its last MoveActorReq of the walk, repeated as captured: the same position), so that U-1's arm / drain requests,
which run at the exit of user 2's next Req on the server's thread, have Reqs to run at. Then the native goodbye
(logout_session) and its two Acks, as the walk script ends.

    py -I -B tools\\scripts\\make_u1_idle_script.py docs\\research\\data\\grapple_s25_g1_walk_138_217.troc ^
        build\\e2e\\u1_idle.troc --minutes 15 --every-ms 1000

The output is a local file (about 1.3 KB per Req): not checked in, not listed in check_troc_scripts.py.
Game build 1.0.0.2976 (the opcodes and payloads are the walk script's).
"""
import argparse
import sys


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("walk", help="a walk script that ends with: wait / logout_session / expect 2003 / expect 2002")
    ap.add_argument("out")
    ap.add_argument("--minutes", type=float, default=15.0)
    ap.add_argument("--every-ms", type=int, default=1000)
    a = ap.parse_args()
    with open(a.walk, encoding="utf-8") as f:
        lines = f.read().replace("\r\n", "\n").split("\n")
    # The goodbye block at the end: from the last 'logout_session' back to the 'wait' before it.
    try:
        bye = max(i for i, s in enumerate(lines) if s.strip() == "logout_session")
    except ValueError:
        sys.exit("no logout_session in the walk script")
    head_end = bye
    if head_end > 0 and lines[head_end - 1].startswith("wait "):
        head_end -= 1
    head = lines[:head_end]
    tail = [s for s in lines[bye:] if s.strip()]
    # The last MoveActorReq of the walk and its put lines.
    last = max((i for i, s in enumerate(head) if s.startswith("send MoveActorReq ")), default=-1)
    if last < 0:
        sys.exit("no MoveActorReq in the walk script")
    req = [head[last].split("  #")[0]]
    j = last + 1
    while j < len(head) and head[j].startswith("put "):
        req.append(head[j])
        j += 1
    count = max(1, int(a.minutes * 60_000 / a.every_ms))
    out = [
        f"# P8 option U, U-1 one-PC test: {a.walk.replace(chr(92), '/')} up to its goodbye, then user 2 stands still for",
        f"# {a.minutes:g} min: its last MoveActorReq repeated {count} times, one every {a.every_ms} ms (U-1's requests run",
        "# at the exit of user 2's next Req). Generated by tools/scripts/make_u1_idle_script.py; not checked in.",
    ] + head + ["", f"# Standing still: {count} x the last MoveActorReq, every {a.every_ms} ms."]
    for _ in range(count):
        out.append(f"wait {a.every_ms}")
        out.extend(req)
    out += ["wait 2000"] + tail
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print(f"{a.out}: {len(head)} lines of the walk, {count} Reqs standing still, then the goodbye")


if __name__ == "__main__":
    main()
