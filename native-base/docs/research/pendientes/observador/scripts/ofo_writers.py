"""ofo_writers.py <broadcast_scan.txt> > src/mod/session2/owner_fanout_writers.h

P8 B step 2 (owner_fanout probe): for every Ack writer that a ToTarget or a ToControlUser finder reaches
(both share vf1 0x2A757F0; build 1.0.0.2976), the return RVA of its `finder->vf1(finder, &array)` call:
the first `call qword ptr [reg+8]` after the `lea reg,[rax+0x2B0]` of the TLS array, within the
writer's first 80 instructions. vf1 sees that return address, so the table maps it back to the writer
and its opcode. Reads the PE through pedis.py (read only).

ToControlUser: broadcast_scan.txt only sees the two `lea` of its vtable (0x2979A5B -> 2339, and its
constructor .xtls 0x104EBDD0). The constructor is reached through the stub 0x2A76060, called from 9 sites
(xref over the PE, 2026-10-10); the writer after each is in TO_CONTROL_USER_CTOR_WRITERS below.
"""
import os
import re
import sys
from collections import defaultdict

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import pedis as D  # noqa: E402

RX = re.compile(r"^(\S+)\s+site (0x[0-9a-f]+) in (0x[0-9a-f]+)\s+-> writer (0x[0-9a-f]+): (\w+)\((\d+)\)")
BASE = 0x140000000
# Writers after a call to the ToControlUser constructor stub 0x2A76060 (site -> writer).
TO_CONTROL_USER_CTOR_WRITERS = {
    0x29B13C0: ("LevelGimmickMapIconUpdatedAck", 2979),  # 0x28C11D6
    0x29FA080: ("RoyalSupplyDataListAck", 3018),         # 0x28D5C6A, 0x28D628B
    0x2966ED0: ("ChangeActionSessionIDAck", 2954),       # 0x2A796F5, 0x2BCF270
    0x29746B0: ("MoveForceNak", 2652),                   # 0x2BCCE1F
    0x2973900: ("ChangeMoveSessionIDAck", 3097),         # 0x2BCCE53, 0x2BCF23B
    0x2A6D5E0: ("ReserveSummonAndRideAck", 2184),        # 0x2C1A2F9
}
KIND_TO_TARGET, KIND_TO_CONTROL_USER = 1, 2


def main(scan_path):
    writers, finders = {}, defaultdict(set)
    for line in open(scan_path, encoding="utf-8", errors="replace"):
        m = RX.match(line.strip())
        if not m:
            continue
        fnd, _site, _fn, w, name, op = m.groups()
        w = int(w, 16)
        writers[w] = (name, int(op))
        finders[w].add(fnd.replace("SendTargetFinder", ""))
    for w, (name, op) in TO_CONTROL_USER_CTOR_WRITERS.items():
        writers.setdefault(w, (name, op))
        finders[w].add("ToControlUser")
    rows, bad = [], []
    for w, (name, op) in sorted(writers.items()):
        kind = (KIND_TO_TARGET if "ToTarget" in finders[w] else 0) | (
            KIND_TO_CONTROL_USER if "ToControlUser" in finders[w] else 0)
        if not kind:
            continue
        found, seen_tls = None, False
        for n, ins in enumerate(D.md.disasm(D.rd(w, 0x600), BASE + w)):
            if ins.mnemonic == "lea" and ins.op_str.endswith("+ 0x2b0]"):
                seen_tls = True
            if seen_tls and ins.mnemonic == "call":
                if re.fullmatch(r"qword ptr \[r\w+ \+ 8\]", ins.op_str):
                    found = ins.address + ins.size - BASE
                break
            if n >= 80 or ins.mnemonic == "ret":
                break
        if found is None:
            bad.append((w, name, op))
        else:
            rows.append((found, w, op, kind, name))
    rows.sort()
    rets = [r[0] for r in rows]
    assert len(rets) == len(set(rets)), "two writers share a return address"
    n_tcu = sum(1 for r in rows if r[3] & KIND_TO_CONTROL_USER)
    print("#pragma once")
    print("// GENERATED by docs/research/pendientes/observador/scripts/ofo_writers.py from")
    print("// build/research/appearance/broadcast_scan.txt, the ToControlUser constructor's callers and the PE of")
    print("// build 1.0.0.2976 (read only). Do not edit.")
    print("// Every Ack writer a ToTarget or ToControlUser finder reaches (both share vf1 0x2A757F0): the return")
    print("// RVA of its finder->vf1 call (what vf1 sees as its return address), the writer, the opcode it writes")
    print("// and which finders reach it.")
    print(f"// {len(rows)} writers ({n_tcu} reached by ToControlUser); {len(bad)} without a recognisable vf1 call.")
    print()
    print("#include <cstdint>")
    print()
    print("namespace cdmp::session2::ofo {")
    print()
    print("inline constexpr uint8_t kByToTarget = 1, kByToControlUser = 2;")
    print()
    print("struct WriterRow {")
    print("    uint32_t ret;     // RVA right after `call [reg+8]` (finder->vf1)")
    print("    uint32_t writer;  // RVA of the writer function")
    print("    uint16_t opcode;")
    print("    uint8_t finders;  // kByToTarget | kByToControlUser")
    print("    const char* name;")
    print("};")
    print()
    print("// Sorted by ret (binary search).")
    print("inline constexpr WriterRow kWriters[] = {")
    for ret, w, op, kind, name in rows:
        print(f"    {{0x{ret:X}, 0x{w:X}, {op}, {kind}, \"{name}\"}},")
    print("};")
    print()
    print("}  // namespace cdmp::session2::ofo")
    if bad:
        print("BAD:", bad, file=sys.stderr)


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else r"C:\Emulador CD\build\research\appearance\broadcast_scan.txt")
