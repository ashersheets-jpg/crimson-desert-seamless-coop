"""Turns an option D login script (JSON, docs/research/data/login_script_*.json)
into the line format cdmp_peer --mode replay plays (src/common/troc_script.h).

    python tools/scripts/make_troc_script.py docs/research/data/login_script_112627.json \
        --stage E3 [--optional] > docs/research/data/login_e3_112627.troc

--stage E2 stops after the user login; E3 goes on with the character and the
two load cycles. Optional steps are left out unless --optional. Ack opcodes
for `learn` come from docs/research/data/troc_messages_2976.csv (by name).

Steps with a "variant" are left out unless asked for: --child-action adds the
"child" ones (D-53r: the first action of user 2's own child after the shared
load, learned with learn_child / learn_child_hash). --goodbye-after-ms adds
the native goodbye at the end (C4a), --comment lines go on top, and --out
writes the file with LF line ends. The two goodbye scripts:

    ... --stage E3 --loading-complete 00 --goodbye-after-ms 20000 \
        --comment "C4a (D-49): ..." --out docs/research/data/login_e3lc00bye_112627.troc
    ... --stage E3 --loading-complete 00 --child-action --goodbye-after-ms 20000 \
        --comment "D-53r: ..." --out docs/research/data/login_e3lc00bye_child_112627.troc

--end-after-step N stops right after step N (and its expect): user 2 vanishes
in the middle of a load (docs/research/pendientes/salida-en-carga.md). With
--goodbye-after-ms the goodbye follows the cut instead (logout mid-load with
the link alive). The cut scripts (flags in check_troc_scripts.py):

    ... --stage E3 --loading-complete 00 --end-after-step 8 --out .../login_e3lc00cut8_112627.troc
"""
import argparse
import csv
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CSV = os.path.join(HERE, "..", "..", "docs", "research", "data", "troc_messages_2976.csv")
TYPES = {1: "u8", 2: "u16", 4: "u32", 8: "u64"}
STAGES = ["E2", "E3", "E4"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("json")
    ap.add_argument("--stage", default="E2", choices=STAGES)
    ap.add_argument("--optional", action="store_true", help="include the optional steps")
    ap.add_argument("--loading-complete", default=None, metavar="HEX",
                    help="payload of every LoadingCompleteReq (the capture has 01; 00 skips copying user 2's "
                         "saved time into the server's world time, opcion-d-e3-riesgos.md R1)")
    ap.add_argument("--settle-ms", type=int, default=5000,
                    help="pause after the last MoveFieldCompleteAck (the big burst)")
    ap.add_argument("--child-action", action="store_true",
                    help="include the 'child' variant steps (D-53r: the first action of user 2's child)")
    ap.add_argument("--goodbye-after-ms", type=int, default=None, metavar="MS",
                    help="end with the native goodbye (logout_session, C4a) after this pause")
    ap.add_argument("--end-after-step", default=None, metavar="N",
                    help="stop the script right after step N (its expect), leaving the rest of the load "
                         "undone (salida-en-carga.md: user 2's link lost in the middle of a load)")
    ap.add_argument("--comment", action="append", default=[], help="a comment line for the top (repeatable)")
    ap.add_argument("--out", default=None, help="write here (LF line ends) instead of stdout")
    a = ap.parse_args()

    d = json.load(open(a.json, encoding="utf-8"))
    ops = {}
    with open(CSV, encoding="utf-8") as f:
        for row in csv.DictReader(f):
            ops[row["name"]] = int(row["id"])
    variants = {"child"} if a.child_action else set()

    def wanted_variant(st):
        return st.get("variant") is None or st["variant"] in variants

    out = []
    w = out.append
    for c in a.comment:
        w(f"# {c}")
    w(f"# Generated by tools/scripts/make_troc_script.py from {os.path.basename(a.json)}")
    w(f"# Game build {d.get('build', '?')}, capture {d.get('source_capture', '?')}; stage {a.stage}"
      f"{', with optional steps' if a.optional else ''}"
      f"{'; LoadingCompleteReq ' + a.loading_complete if a.loading_complete is not None else ''}"
      f"{'; with the child variant' if a.child_action else ''}"
      f"{'; cut after step ' + a.end_after_step if a.end_after_step is not None else ''}.")
    w("# Override variables with cdmp_peer --var NAME=VALUE (SAVE_SLOT = the host's slot in E3).")
    w("var ACCOUNT u64 1")
    w("var SAVE_SLOT u32 1  # slot of capture 112627")
    want = STAGES[: STAGES.index(a.stage) + 1]
    steps = [s for s in d["steps"] if s["stage"] in want and (a.optional or not s.get("optional"))
             and wanted_variant(s)]
    declared = {"ACCOUNT", "SAVE_SLOT"}
    for st in steps:
        for v in st.get("declare", []):
            declared.add(v["var"])
            w(f"var {v['var']} {TYPES[v['size']]} {v['value']}  # {v.get('meaning', '')}".rstrip(" #"))
    learned = set()
    for st in d["steps"]:
        if not wanted_variant(st):
            continue
        for c in st.get("capture_from_acks", []):
            if c["var"] in learned:
                continue
            learned.add(c["var"])
            w(f"learn {c['var']} {TYPES[c['size']]} {ops[c['ack']]} {c['offset']}  # {c['ack']}")
    for st in steps:
        c = st.get("capture_child")
        if not c:
            continue
        types = ",".join(str(t) for t in c.get("types", [4, 5, 6]))
        w(f"learn_child {c['var']} {ops[c['ack']]} {c['owner']} {types}  # {c['ack']}: user 2's own child")
        learned.add(c["var"])
        if c.get("hash_var"):
            w(f"learn_child_hash {c['hash_var']}  # its layer-0 action hash, if its CC block parses")
            learned.add(c["hash_var"])
    for r in d.get("reactive", []):
        w(f"# reactive: on {r['on']} send {r['send']} ({r.get('note', '')})")
        if a.optional and r["send"] == "EchoMoveSessionIDReq":
            # u32 actor key (= Ack @0) | u32 id (= Ack @8) | u32 0. The player
            # cannot check "Ack @4 == USER_KEY": it answers every one.
            w(f"learn MS_KEY u32 {r['opcode']} 0")
            w(f"learn MS_ID u32 {r['opcode']} 8")
            w(f"reply {r['opcode']} {r['send_opcode']} {r['slot']} {'00' * 12}")
            w("put u32 0 MS_KEY")
            w("put u32 4 MS_ID")

    last_mfc = max((i for i, s in enumerate(steps) if s["name"] == "MoveFieldCompleteReq"), default=-1)
    # The settle pause goes after the variant steps that follow the last
    # MoveFieldCompleteReq (the child's action goes right after its record,
    # as the real client sends it, not 5 s later).
    settle_after = last_mfc
    while settle_after >= 0 and settle_after + 1 < len(steps) and steps[settle_after + 1].get("variant"):
        settle_after += 1
    if a.end_after_step is not None:
        cut = [i for i, s in enumerate(steps) if str(s["n"]) == a.end_after_step]
        if not cut:
            sys.exit(f"--end-after-step {a.end_after_step}: no such step in stage {a.stage}")
        steps = steps[: cut[0] + 1]
        settle_after = -1  # the cut scripts go silent right after the Ack
    for i, st in enumerate(steps):
        w("")
        w(f"# {st['n']}. {st['name']} (channel {st.get('canal')}){' [optional]' if st.get('optional') else ''}"
          f"{' [' + st['variant'] + ']' if st.get('variant') else ''}")
        wl = st.get("wait_learned")
        if wl:
            w(f"expect_learned {wl['var']} {wl['timeout_ms']}")
        if st.get("delay_ms_before"):
            w(f"wait {st['delay_ms_before']}")
        payloads = st.get("hex_list") or [st.get("hex") or ""]
        if st["name"] == "LoadingCompleteReq" and a.loading_complete is not None:
            payloads = [a.loading_complete]
        for k, hx in enumerate(payloads):
            label = st["name"] if len(payloads) == 1 else f"{st['name']}.{k + 1}"
            w(f"send {label} {st['opcode']} {st['slot']} {hx or '-'}")
            for r in st.get("rewrite", []):
                if r.get("source") in declared or r.get("source") in learned:
                    off = r["offset"] if r["offset"] < 0x10 else f"0x{r['offset']:X}"
                    w(f"put {TYPES[r['size']]} {off} {r['source']}")
        exp = st.get("expect")
        if exp:
            w(f"expect {exp['opcode']} 30000  # {exp['name']}")
        elif st.get("delay_ms_after"):
            w(f"wait {st['delay_ms_after']}")
        if i == settle_after and a.stage != "E2":
            w(f"wait {a.settle_ms}  # let the burst of ActorLoadDataAck finish")
    if a.end_after_step is not None and a.goodbye_after_ms is None:
        w("")
        w(f"# Cut after step {a.end_after_step}: the rest of the load is never sent. cdmp_peer goes silent")
        w("# (--linger) and exits; the host's C4 sees the link lost and hands the 2001 mid-load.")
        w("end")
    if a.goodbye_after_ms is not None:
        w("")
        w(f"# C4a. Goodbye after {a.goodbye_after_ms / 1000:g} s in the host's field")
        w(f"wait {a.goodbye_after_ms}")
        w("logout_session")
        w(f"expect {ops['LogoutUserToServerAck']} 30000  # LogoutUserToServerAck")
        w(f"expect {ops['LogoutSessionToServerAck']} 30000  # LogoutSessionToServerAck")
    text = "\n".join(out) + "\n"
    if a.out:
        with open(a.out, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
